"""The CV obeys published ATS parsing rules.

Written after a user reported the generated CV "doesn't look like a CV, it's just stating
facts". The formatting rules below are not taste -- they are the mechanical constraints
applicant tracking systems and their vendors publish, and the previous template broke
several at once: a two-column flex row for dates, an invented "APPLYING FOR" heading, body
content in a <footer>, and separators made of CSS generated content.

Sources for the rules: Jobscan's ATS resume format checklist, and the XYZ bullet formula
(Laszlo Bock) for content.
"""

from __future__ import annotations

import re
from uuid import uuid4

import pytest
from localapply.documents.generator import DocumentGenerator
from localapply.documents.render import build_contact_line, render_html
from localapply.documents.taxonomy import group_skills, is_presentable
from localapply.profile.facts import FactCategory, FactStatus

JOB = "Requirements:\n- Python\n- FastAPI\n- Docker\n\nNice to have:\n- Kubernetes\n"


class Fact:
    def __init__(self, key, value, category, detail=None):
        self.id = uuid4()
        self.key, self.value, self.category = key, value, category
        self.detail = detail or {}
        self.status = FactStatus.ACCEPTED.value


@pytest.fixture
def facts():
    return [
        Fact("full_name", "Haydar Farhat", FactCategory.IDENTITY.value),
        Fact("current_title", "AI Engineer", FactCategory.IDENTITY.value),
        Fact("email", "h@example.com", FactCategory.IDENTITY.value),
        Fact("phone", "+961 76 943 608", FactCategory.IDENTITY.value),
        Fact("city", "Beirut", FactCategory.IDENTITY.value),
        Fact("country", "Lebanon", FactCategory.IDENTITY.value),
        Fact("linkedin_url", "https://www.linkedin.com/in/haydar/", FactCategory.IDENTITY.value),
        Fact("Python", "Python", FactCategory.SKILL.value),
        Fact("Laravel", "Laravel", FactCategory.SKILL.value),
        Fact("Docker", "Docker", FactCategory.SKILL.value),
        Fact("OOP", "OOP", FactCategory.SKILL.value),
        Fact("phrase", "Python-based AI workflows", FactCategory.SKILL.value),
        Fact(
            "Full-Stack Developer — Carepool",
            "Full-Stack Developer — Carepool",
            FactCategory.EXPERIENCE.value,
            {
                "role": "Full-Stack Developer", "organisation": "Carepool",
                "dates": "2023 - Present",
                "bullets": ["Engineered backend services and REST APIs using Laravel."],
            },
        ),
    ]


@pytest.fixture
def cv(facts):
    return render_html(
        DocumentGenerator().tailored_cv(
            facts, job_title="AI Engineer", company="Northwind", description=JOB
        )
    )


def body_of(html: str) -> str:
    return html.split("</style>", 1)[1]


# --------------------------------------------------------------------------------------
# Layout: single column, no constructs parsers cannot read
# --------------------------------------------------------------------------------------


def test_no_tables_or_text_boxes(cv):
    for tag in ("<table", "<td", "<tr", "<textarea", "<img", "<svg", "<canvas"):
        assert tag not in cv.lower(), f"{tag} is not ATS-parseable"


def test_no_multi_column_layout(cv):
    """The old template used `display: flex; justify-content: space-between` to right-align
    dates -- a two-column row inside the content."""
    styles = cv.split("</style>")[0]
    for rule in ("display: flex", "display:flex", "display: grid", "display:grid",
                 "column-count", "float:", "float :"):
        assert rule not in styles, f"{rule!r} creates a multi-column layout"


def test_nothing_in_a_header_or_footer_element(cv):
    """Parsers routinely drop header/footer content, and the old footer's "Generated by
    LocalApply from N verified profile facts" was noise on a document sent to an employer --
    a variant of it even leaked into the body as a bullet."""
    assert "<footer" not in cv.lower()
    assert "<header" not in cv.lower()
    assert "Generated by LocalApply" not in cv


def test_no_css_generated_content(cv):
    """`::after { content: ... }` renders but is not document text; a contact line must
    never depend on it."""
    styles = cv.split("</style>")[0]
    assert "content:" not in styles.replace("box-sizing", "")
    assert "::after" not in styles
    assert "::before" not in styles


def test_web_safe_font_stack(cv):
    styles = cv.split("</style>")[0]
    assert re.search(r"font-family:\s*(Calibri|Arial|Georgia|Helvetica|Times)", styles), (
        "body font must be one a parser and a printer both have"
    )


def test_bullets_are_a_real_list(cv):
    assert "<ul" in cv and "<li>" in cv
    assert "list-style-type: disc" in cv.split("</style>")[0]


