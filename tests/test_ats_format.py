# Structure: standard headings only
# --------------------------------------------------------------------------------------


STANDARD_HEADINGS = {"SUMMARY", "SKILLS", "EXPERIENCE", "PROJECTS", "EDUCATION",
                     "CERTIFICATIONS", "WORK EXPERIENCE"}


def test_only_standard_section_headings(cv):
    headings = {h.strip().upper() for h in re.findall(r"<h2>(.*?)</h2>", cv, re.DOTALL)}
    unexpected = headings - STANDARD_HEADINGS
    assert not unexpected, f"non-standard headings a parser cannot bucket: {unexpected}"


def test_the_company_applied_to_is_not_printed(cv):
    assert "Northwind" not in cv
    assert "APPLYING FOR" not in cv.upper()


