def test_skills_are_grouped_not_a_wall(cv):
    body = body_of(cv)
    assert "Languages:" in body, "skills should be grouped for a reader who skims"
    assert "Python" in body


def test_cs_topics_and_phrases_are_not_listed_as_skills(cv):
    body = body_of(cv)
    assert "OOP" not in body
    assert "Python-based AI workflows" not in body


def test_taxonomy_keeps_real_technologies():
    for skill in ("Python", "Laravel", "React Native", "MySQL", "Docker", "RAG"):
        assert is_presentable(skill), f"{skill} is a real skill and must survive"


def test_taxonomy_groups_in_conventional_order():
    groups = [name for name, _ in group_skills(["Docker", "Python", "MySQL", "Laravel"])]
    assert groups.index("Languages") < groups.index("Frameworks") < groups.index(
        "Tools & Platforms"
    )


