def test_role_employer_and_dates_are_on_one_text_line(cv):
    """Inline rather than right-aligned in a second column, so the reading order a parser
    sees matches the reading order a person sees."""
    head = re.search(r'<p class="entry-head">(.*?)</p>', cv, re.DOTALL)
    assert head is not None
    text = re.sub(r"<[^>]+>", "", head.group(1))
    assert "Full-Stack Developer" in text
    assert "Carepool" in text
    assert "2023 - Present" in text


def test_bullets_are_separate_from_the_headline(cv):
    head = re.search(r'<p class="entry-head">(.*?)</p>', cv, re.DOTALL).group(1)
    assert "Engineered backend services" not in head, (
        "a bullet must not be merged into the role line"
    )
    assert "<li>Engineered backend services" in cv.replace("\n", "").replace("  ", "")
